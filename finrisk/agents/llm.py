def parse_json_response(text: str) -> dict[str, Any]:
    """Extract the first JSON object from an LLM response.

    Models wrap JSON in prose or fences despite instructions, so this strips
    fences and falls back to brace matching rather than failing the pipeline.
    """
    cleaned = re.sub(r"```(?:json)?", "", text).strip()
    try:
        obj = json.loads(cleaned)
        return obj if isinstance(obj, dict) else {"value": obj}
    except json.JSONDecodeError:
        pass
    start = cleaned.find("{")
    if start >= 0:
        depth = 0
        for i, ch in enumerate(cleaned[start:], start):
            depth += ch == "{"
            depth -= ch == "}"
            if depth == 0:
                try:
                    return json.loads(cleaned[start : i + 1])
                except json.JSONDecodeError:
                    break
    logger.warning("could not parse JSON from LLM response")
    return {}


def _extract_json_blocks(prompt: str) -> dict[str, Any]:
    """Recover the structured facts embedded in a prompt."""
    out: dict[str, Any] = {}
    for match in re.finditer(r"<facts:([a-z_]+)>\s*(\{.*?\}|\[.*?\])\s*</facts:\1>", prompt, re.S):
        try:
            out[match.group(1)] = json.loads(match.group(2))
        except json.JSONDecodeError:
            continue
    return out


def _detect_role(system: str) -> str:
    s = system.lower()
    for role in ("bull", "bear", "risk", "quant", "research"):
        if f"role: {role}" in s:
            return role
    return "generic"


def _fmt_pct(x: Any) -> str:
    try:
        return f"{float(x):.2%}"
    except (TypeError, ValueError):
        return "n/a"


def _fmt_num(x: Any, nd: int = 2) -> str:
    try:
        return f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return "n/a"


def _stub_summary(facts: dict[str, Any]) -> str:
    port = facts.get("portfolio") or {}
    risk = facts.get("risk") or {}
    regime = facts.get("regime") or {}
    n = len(port.get("weights", {}) or {})
    return (
        f"Portfolio of {n} positions constructed by {port.get('method', 'unknown')}. "
        f"Ex-ante volatility {_fmt_pct(port.get('expected_volatility_ann'))}, "
        f"realised volatility {_fmt_pct(risk.get('ann_volatility'))}, "
        f"CVaR 95% {_fmt_pct(risk.get('cvar_95'))}. "
        f"Detected regime: {regime.get('regime', 'unknown')} "
        f"(confidence {_fmt_num(regime.get('confidence'))})."
    )


def _stub_research(facts: dict[str, Any], prompt: str) -> dict[str, Any]:
    port = facts.get("portfolio") or {}
    risk = facts.get("risk") or {}
    regime = facts.get("regime") or {}
    factors = facts.get("factors") or {}
    cits = facts.get("citations") or []

    quant = {
        k: v
        for k, v in {
            "expected_volatility_ann": port.get("expected_volatility_ann"),
            "expected_return_ann": port.get("expected_return_ann"),
            "sharpe_ex_ante": port.get("sharpe_ex_ante"),
            "realised_volatility": risk.get("ann_volatility"),
            "cvar_95": risk.get("cvar_95"),
            "var_95_hist": risk.get("var_95_hist"),
            "max_drawdown": risk.get("max_drawdown"),
            "effective_n": risk.get("effective_n"),
        }.items()
        if isinstance(v, (int, float))
    }

    support: list[str] = []
    contra: list[str] = []
    risks: list[str] = []
    top = (factors.get("ranking") or [])[:3]
    if top:
        support.append(
            "Selected names rank highest on the composite factor score: "
            + ", ".join(
                f"{r['ticker']} (rank {r['rank']}, score {_fmt_num(r['composite'])})" for r in top
            )
        )
    if quant.get("expected_volatility_ann") is not None:
        support.append(
            f"Ex-ante volatility {_fmt_pct(quant['expected_volatility_ann'])} is within "
            "the configured risk limit; the optimiser reported the constraint as satisfied."
        )
    if regime.get("regime"):
        (support if regime["regime"] == "risk_on_low_vol" else contra).append(
            f"Detected regime is {regime['regime']} with confidence "
            f"{_fmt_num(regime.get('confidence'))}, implying an exposure multiplier of "
            f"{_fmt_num(regime.get('risk_multiplier'))}."
        )
    if quant.get("cvar_95") is not None:
        risks.append(
            f"One-day CVaR at 95% is {_fmt_pct(quant['cvar_95'])}; tail losses exceed "
            "the Gaussian estimate when returns are negatively skewed."
        )
    if quant.get("effective_n") is not None and quant["effective_n"] < 8:
        risks.append(
            f"Effective number of positions is {_fmt_num(quant['effective_n'])}, "
            "indicating concentration despite the per-name weight cap."
        )
    for flag in risk.get("concentration_flags") or []:
        # Skip flags already covered above, so the same concern is not stated twice.
        if "effective number" in str(flag).lower() and any("Effective number" in r for r in risks):
            continue
        risks.append(str(flag))
    contra.append(
        "Factor premia are estimated from a finite sample; the information "
        "coefficient used to scale alpha is small and unstable across sub-periods."
    )

    return {
        "thesis": _stub_summary(facts),
        "supporting_evidence": support,
        "contradicting_evidence": contra,
        "quantitative_evidence": quant,
        "risk_factors": risks,
        "confidence": 0.5,
        "sources": cits[:5],
    }


def _stub_opinion(role: str, facts: dict[str, Any]) -> dict[str, Any]:
    port = facts.get("portfolio") or {}
    risk = facts.get("risk") or {}
    regime = facts.get("regime") or {}
    bt = facts.get("backtest") or {}

    cited = {
        k: v
        for k, v in {
            "expected_return_ann": port.get("expected_return_ann"),
            "expected_volatility_ann": port.get("expected_volatility_ann"),
            "cvar_95": risk.get("cvar_95"),
            "max_drawdown": risk.get("max_drawdown"),
            "sharpe_backtest": bt.get("sharpe"),
            "cagr_backtest": bt.get("cagr"),
            "avg_turnover": bt.get("avg_turnover"),
        }.items()
        if isinstance(v, (int, float))
    }

    if role == "bull":
        return {
            "role": "bull",
            "stance": "support",
            "argument": " ".join(
                [
                    f"The construction delivers an ex-ante Sharpe of "
                    f"{_fmt_num(port.get('sharpe_ex_ante'))} with volatility held to "
                    f"{_fmt_pct(port.get('expected_volatility_ann'))}.",
                ]
                + (
                    [
                        f"Walk-forward CAGR was {_fmt_pct(bt['cagr'])} against realised "
                        f"volatility of {_fmt_pct(bt.get('ann_volatility'))}."
                    ]
                    if isinstance(bt.get("cagr"), (int, float))
                    else []
                )
            ),
            "cited_metrics": cited,
            "concerns": [],
        }
    if role == "bear":
        # Only assert what the facts actually contain. Earlier this emitted
        # "Maximum drawdown of n/a" when no backtest had been run — a sentence
        # that reads like evidence while carrying none.
        parts = []
        if isinstance(risk.get("cvar_95"), (int, float)):
            parts.append(
                f"One-day CVaR of {_fmt_pct(risk['cvar_95'])} indicates losses cluster in the tail."
            )
        if isinstance(bt.get("max_drawdown"), (int, float)):
            parts.append(f"Walk-forward maximum drawdown reached {_fmt_pct(bt['max_drawdown'])}.")
        if isinstance(bt.get("total_cost_drag"), (int, float)):
            parts.append(
                f"Cumulative cost drag of {_fmt_pct(bt['total_cost_drag'])} was required "
                "to earn the reported return."
            )
        if isinstance(risk.get("effective_n"), (int, float)) and risk["effective_n"] < 8:
            parts.append(
                f"Effective N of {_fmt_num(risk['effective_n'])} leaves the portfolio concentrated."
            )
        if not parts:
            parts.append(
                "The available evidence is insufficient to establish that this "
                "allocation is prudent; no walk-forward result was supplied."
            )
        return {
            "role": "bear",
            "stance": "oppose",
            "argument": " ".join(parts),
            "cited_metrics": cited,
            "concerns": [
                "Performance is measured on a single dataset and a single parameter set.",
                "Transaction-cost assumptions are simplified and could be optimistic.",
            ],
        }
    if role == "risk":
        flags = risk.get("concentration_flags") or []
        return {
            "role": "risk",
            "stance": "conditional" if flags else "support",
            "argument": (
                f"Realised volatility {_fmt_pct(risk.get('ann_volatility'))} against a target of "
                f"{_fmt_pct(port.get('expected_volatility_ann'))}; effective N is "
                f"{_fmt_num(risk.get('effective_n'))}. "
                + (
                    f"{len(flags)} concentration flag(s) raised."
                    if flags
                    else "No concentration limits breached."
                )
            ),
            "cited_metrics": cited,
            "concerns": [str(f) for f in flags],
        }
    return {
        "role": "quant",
        "stance": "conditional",
        "argument": (
            "Signals are deterministic and reproducible from the config digest. "
            f"Regime inference is filtered, not smoothed ({regime.get('regime', 'n/a')}). "
            "The alpha scale derives from an out-of-sample IC estimate, so the forecast "
            "magnitude is not fitted to the evaluation window."
        ),
        "cited_metrics": cited,
        "concerns": [
            "IC estimates are noisy; alpha scaling is the least robust input.",
            "Covariance shrinkage reduces but does not eliminate estimation error.",
        ],
    }
