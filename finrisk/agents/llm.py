"""LLM abstraction for the agent layer.

Two backends:

* `StubLLM` — **deterministic template narrator**, not a language model. It
  composes prose from the structured tool output it is handed. It exists so the
  entire agent graph runs in CI with no API key, no network and no
  non-determinism, and so that `tests/test_agents.py` asserts on exact strings.
  It is honestly named: nothing here simulates model intelligence.

* `AnthropicLLM` — the real thing, used when `ANTHROPIC_API_KEY` is present and
  `AgentConfig.llm_provider == "anthropic"`.

Both satisfy the same `LLMClient` protocol, and — this is the important part —
neither is ever given the ability to emit a portfolio weight. Their output is
parsed into `ResearchConclusion` / `CommitteeOpinion` objects whose numeric
fields are *copied from tool results*, then checked by the critic
(`finrisk/agents/critic.py`). A hallucinated figure fails validation and is
stripped before it can reach a report.
"""

from __future__ import annotations

import json
import logging
import os
import re
from typing import Any, Protocol

logger = logging.getLogger(__name__)


class LLMClient(Protocol):
    name: str

    def complete(self, system: str, prompt: str, max_tokens: int = 1500) -> str: ...


# ----------------------------------------------------------------------


class StubLLM:
    """Deterministic narrator. Same input -> byte-identical output."""

    name = "stub"

    def __init__(self) -> None:
        self.n_calls = 0

    def complete(self, system: str, prompt: str, max_tokens: int = 1500) -> str:
        self.n_calls += 1
        facts = _extract_json_blocks(prompt)
        role = _detect_role(system)

        if role == "research":
            return json.dumps(_stub_research(facts, prompt), indent=2)
        if role in {"bull", "bear", "risk", "quant"}:
            return json.dumps(_stub_opinion(role, facts), indent=2)
        return json.dumps(
            {
                "summary": _stub_summary(facts),
                "note": "generated by the deterministic stub narrator",
            },
            indent=2,
        )


class AnthropicLLM:
    """Anthropic Messages API backend."""

    name = "anthropic"

    def __init__(self, model: str = "claude-sonnet-4-6", temperature: float = 0.0) -> None:
        self.model = model
        self.temperature = temperature
        self.n_calls = 0
        self.total_input_tokens = 0
        self.total_output_tokens = 0
        key = os.environ.get("ANTHROPIC_API_KEY")
        if not key:
            raise RuntimeError(
                "ANTHROPIC_API_KEY not set. Use llm_provider='stub' for offline runs."
            )
        try:
            import anthropic
        except ImportError as exc:  # pragma: no cover - optional dep
            raise ImportError("pip install anthropic") from exc
        self._client = anthropic.Anthropic(api_key=key)

    def complete(self, system: str, prompt: str, max_tokens: int = 1500) -> str:
        self.n_calls += 1
        resp = self._client.messages.create(
            model=self.model,
            max_tokens=max_tokens,
            temperature=self.temperature,
            system=system,
            messages=[{"role": "user", "content": prompt}],
        )
        usage = getattr(resp, "usage", None)
        if usage is not None:
            self.total_input_tokens += getattr(usage, "input_tokens", 0) or 0
            self.total_output_tokens += getattr(usage, "output_tokens", 0) or 0
        return "".join(block.text for block in resp.content if getattr(block, "type", "") == "text")


def build_llm(provider: str, model: str, temperature: float = 0.0) -> LLMClient:
    if provider == "anthropic":
        try:
            return AnthropicLLM(model, temperature)
        except Exception as exc:
            logger.warning("Anthropic backend unavailable (%s); using stub", exc)
            return StubLLM()
    return StubLLM()


