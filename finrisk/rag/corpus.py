"""Synthetic filing corpus for the RAG layer.

Real filings cannot be bundled (copyright, size, and this sandbox has no network
access to EDGAR), and inventing text about *real* companies would fabricate
financial facts — explicitly forbidden by the project brief.

So the offline corpus is generated for the synthetic universe, and every
document is derived from that universe's **actual** fundamental records. A
retrieved sentence such as "book value per share of 43.86" is therefore true of
the dataset the backtest ran on: the RAG answers are internally consistent and
checkable, rather than decorative.

For real use, drop real filings into `RAGConfig.docs_dir` named
`TICKER_10K_YEAR.txt` and `finrisk.data.documents.load_corpus` will pick them up
with correct ticker/doc-type metadata.
"""

from __future__ import annotations

import logging
from pathlib import Path

import numpy as np
import pandas as pd

from finrisk.data.base import MarketDataBundle

logger = logging.getLogger(__name__)

BANNER = (
    "SYNTHETIC DOCUMENT — generated by FINRISK AI from the synthetic dataset. "
    "This describes a simulated entity and contains no information about any "
    "real company."
)

_RISK_LIBRARY = {
    "Technology": [
        "Rapid product cycles require sustained research and development "
        "expenditure; a delayed release could materially affect revenue.",
        "Revenue is concentrated among a small number of enterprise customers, "
        "and the loss of one could reduce segment revenue significantly.",
        "Component supply is dependent on a limited number of fabrication "
        "partners, exposing the entity to supply disruption.",
    ],
    "Financials": [
        "Net interest income is sensitive to the level and shape of the yield "
        "curve; a rapid decline in policy rates would compress margins.",
        "Credit losses may increase materially in a recession, and current "
        "provisions reflect management estimates that could prove insufficient.",
        "Capital and liquidity requirements are subject to regulatory change.",
    ],
    "Healthcare": [
        "Clinical trial outcomes are inherently uncertain and a failed trial "
        "would reduce the value of the associated development programme.",
        "Reimbursement rates are set by payors and government programmes and "
        "may be reduced without notice.",
        "Patent expiry exposes several products to generic competition.",
    ],
    "Industrials": [
        "Order backlog is sensitive to capital spending cycles and may be "
        "cancelled or deferred by customers.",
        "Input costs, particularly steel and freight, are volatile and may not "
        "be recoverable through pricing in the short term.",
        "Operations are exposed to project execution risk on fixed-price " "contracts.",
    ],
    "Consumer": [
        "Discretionary demand is sensitive to real household income and " "consumer confidence.",
        "Private-label competition may compress gross margin in key categories.",
        "A significant share of revenue is generated through a small number of " "retail partners.",
    ],
    "Energy": [
        "Results are highly sensitive to commodity prices, which are volatile "
        "and outside management control.",
        "Reserve estimates involve significant judgement and may be revised.",
        "Transition and environmental regulation may increase compliance costs "
        "or impair long-lived assets.",
    ],
}


def _fmt(x: float) -> str:
    return f"{x:,.2f}"


def _annual_report(
    ticker: str,
    sector: str,
    year: int,
    rows: pd.DataFrame,
    price: float,
) -> str:
    latest = rows.iloc[-1]
    bvps = float(latest["book_value_per_share"])
    eps = float(latest["eps"])
    fcf = float(latest["free_cash_flow_per_share"])
    debt = float(latest["total_debt_per_share"])
    equity = float(latest["total_equity_per_share"])
    assets = float(latest["total_assets_per_share"])
    rev = float(latest["revenue_per_share"])
    ebitda = float(latest["ebitda_per_share"])
    roe = eps / equity if abs(equity) > 1e-9 else float("nan")
    roa = eps / assets if abs(assets) > 1e-9 else float("nan")
    lev = debt / equity if abs(equity) > 1e-9 else float("nan")
    eps_series = pd.to_numeric(rows["eps"], errors="coerce").dropna()
    trend = (
        "increased"
        if len(eps_series) > 1 and eps_series.iloc[-1] > eps_series.iloc[0]
        else "declined"
    )
    risks = _RISK_LIBRARY.get(sector, _RISK_LIBRARY["Industrials"])

    return f"""{BANNER}

ANNUAL REPORT — Synthetic Corp {ticker}
Fiscal year {year} | Sector: {sector} | Ticker: {ticker}

ITEM 1. BUSINESS
Synthetic Corp {ticker} operates in the {sector.lower()} sector. The entity is a
constituent of the FINRISK AI synthetic research universe and is used to
exercise the document retrieval and research pipeline end to end.

ITEM 7. MANAGEMENT DISCUSSION AND ANALYSIS
Revenue per share for fiscal {year} was {_fmt(rev)}. Earnings per share were
{_fmt(eps)}, and EBITDA per share was {_fmt(ebitda)}. Over the reported
quarters earnings per share {trend}. Free cash flow per share of {_fmt(fcf)}
represented {fcf / eps * 100 if abs(eps) > 1e-9 else float('nan'):.0f} percent of
reported earnings, and management regards cash conversion as the primary
indicator of earnings quality.

Book value per share at year end was {_fmt(bvps)} against a share price of
{_fmt(price)}, implying a book-to-price ratio of
{bvps / price if price > 0 else float('nan'):.3f}. Return on equity was
{roe * 100:.1f} percent and return on assets was {roa * 100:.1f} percent.

CAPITAL STRUCTURE
Total debt per share was {_fmt(debt)} against total equity per share of
{_fmt(equity)}, a debt-to-equity ratio of {lev:.2f}. Total assets per share
were {_fmt(assets)}. Management targets a leverage level consistent with
continued access to unsecured funding.

ITEM 1A. RISK FACTORS
{risks[0]}
{risks[1]}
{risks[2]}
The entity's results are also exposed to broad equity market drawdowns, and
periods of elevated volatility have historically coincided with multiple
compression across the {sector.lower()} sector.

ITEM 8. FINANCIAL STATEMENTS — SELECTED DATA
Earnings per share by reported quarter:
{chr(10).join(f'  {r.period_end}: EPS {float(r.eps):.2f}, book value per share {float(r.book_value_per_share):.2f}' for r in rows.itertuples())}
"""


def _earnings_release(
    ticker: str, sector: str, row: pd.Series, price: float, prev_eps: float | None
) -> str:
    eps = float(row["eps"])
    delta = (
        f"an increase of {(eps / prev_eps - 1) * 100:.1f} percent"
        if prev_eps and abs(prev_eps) > 1e-9 and eps > prev_eps
        else (
            f"a decrease of {abs(eps / prev_eps - 1) * 100:.1f} percent"
            if prev_eps and abs(prev_eps) > 1e-9
            else "no comparable prior period"
        )
    )
    return f"""{BANNER}

QUARTERLY EARNINGS RELEASE — Synthetic Corp {ticker}
Period ended {row['period_end']} | Published {row['available_from']}
Sector: {sector}

Synthetic Corp {ticker} reported earnings per share of {eps:.2f} for the
quarter ended {row['period_end']}, representing {delta} versus the prior
reported quarter. Revenue per share was {float(row['revenue_per_share']):.2f}
and EBITDA per share was {float(row['ebitda_per_share']):.2f}.

Book value per share stood at {float(row['book_value_per_share']):.2f}. Free
cash flow per share was {float(row['free_cash_flow_per_share']):.2f}. The
closing share price on the period end date was {price:.2f}.

Total debt per share was {float(row['total_debt_per_share']):.2f} against total
equity per share of {float(row['total_equity_per_share']):.2f}.

NOTE ON AVAILABILITY
This release was published on {row['available_from']}, which is after the
period end of {row['period_end']}. Any research process that treats the period
end as the availability date would be using information before it existed.
"""


def generate_corpus(
    bundle: MarketDataBundle,
    out_dir: str | Path,
    n_tickers: int = 12,
    years: tuple[int, ...] | None = None,
    clean: bool = False,
) -> list[Path]:
    """Write annual reports and earnings releases for the synthetic universe.

    `years=None` derives the last four fiscal years present in the bundle, so
    the corpus adapts to whatever period was loaded instead of silently
    producing nothing when hardcoded years fall outside the sample.
    `clean=True` removes previously generated files first, which prevents a
    stale corpus from an earlier run (different seed or universe size) from
    being mixed with the current one.
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    if clean:
        for old in list(out.glob("*_10K_*.txt")) + list(out.glob("*_earnings_*.txt")):
            old.unlink()
    fund = bundle.fundamentals.copy()
    if not len(fund):
        logger.warning("bundle has no fundamentals; corpus not generated")
        return []
    fund["period_end"] = pd.to_datetime(fund["period_end"])
    if years is None:
        available = sorted(fund["period_end"].dt.year.unique())
        years = tuple(available[-4:])
        logger.info("corpus years derived from data: %s", years)
    written: list[Path] = []

    tickers = bundle.tickers[:n_tickers]
    for tk in tickers:
        sector = bundle.meta[tk].sector if tk in bundle.meta else "Industrials"
        sub = fund[fund["ticker"] == tk].sort_values("period_end")
        if not len(sub):
            continue
        for year in years:
            rows = sub[sub["period_end"].dt.year == year]
            if not len(rows):
                continue
            pe = rows["period_end"].max()
            px_hist = bundle.prices[tk].loc[:pe]
            price = float(px_hist.iloc[-1]) if len(px_hist) else float("nan")
            if not np.isfinite(price):
                continue
            p = out / f"{tk}_10K_{year}.txt"
            p.write_text(
                _annual_report(
                    tk,
                    sector,
                    year,
                    rows.assign(period_end=rows["period_end"].dt.date),
                    price,
                )
            )
            written.append(p)

            last = rows.iloc[-1].copy()
            last["period_end"] = pd.Timestamp(last["period_end"]).date()
            prev_idx = sub.index.get_indexer([rows.index[-1]])[0] - 1
            prev_eps = float(sub.iloc[prev_idx]["eps"]) if prev_idx >= 0 else None
            q = out / f"{tk}_earnings_{year}Q{pd.Timestamp(pe).quarter}.txt"
            q.write_text(_earnings_release(tk, sector, last, price, prev_eps))
            written.append(q)

    logger.info("wrote %d synthetic documents to %s", len(written), out)
    return written
